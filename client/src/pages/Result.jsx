import React, { useContext, useState } from "react";
import { assets } from "../assets/assets";
import { motion } from "motion/react";
import { AppContext } from "../context/AppContext";
import { Sparkles } from "lucide-react";
import { generateShareableImage } from "../utils/generateShareableImage";
import logo from "/images/pixelfy-logo-icon.png";

const Result = () => {
  const [isImageLoaded, setIsImageLoaded] = useState(false);
  const [loading, setLoading] = useState(false);
  const [image, setImage] = useState(assets.sample_img_1);
  const [selectedFilter, setSelectedFilter] = useState("filter-none");

  const { generateImage, handleEnhancePrompt, enhancing, input, setInput } =
    useContext(AppContext);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setLoading(true);
    if (input) {
      const image = await generateImage(input);
      if (image) {
        setIsImageLoaded(true);
        setImage(image);
      }
    }
    setLoading(false);
  };

  const handleShare = async () => {
    try {
      setLoading(true);
      const brandedImage = await generateShareableImage(
        image,
        logo,
        "Generated by Pixelfy"
      );

      if (navigator.share) {
        // Mobile & supported browsers
        const blob = await (await fetch(brandedImage)).blob();
        const file = new File([blob], "shared-image.png", { type: blob.type });

        await navigator.share({
          title: "Check out my AI-generated image!",
          text: "Created with MyWebsite.com 🎨",
          files: [file],
        });
      } else {
        // Fallback: Open new tab with image to save or copy
        const win = window.open();
        win.document.write(`<img src="${brandedImage}" alt="Share Image"/>`);
      }
    } catch (error) {
      console.error("Share failed:", error);
      alert("Unable to share at the moment.");
    } finally {
      setLoading(false);
    }
  };

  const downloadFilteredImage = () => {
    const img = document.querySelector("img");
    const canvas = document.createElement("canvas");
    const ctx = canvas.getContext("2d");

    canvas.width = img.naturalWidth;
    canvas.height = img.naturalHeight;

    ctx.filter = getComputedStyle(img).filter;
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);

    const link = document.createElement("a");
    link.download = "filtered-image.png";
    link.href = canvas.toDataURL("image/png");
    link.click();
  };

  return (
    <motion.form
      initial={{ opacity: 0.2, y: 100 }}
      transition={{ duration: 1 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true }}
      onSubmit={handleSubmit}
      className="flex flex-col min-h-[90vh] justify-center items-center"
    >
      <div>
        <div className="relative">
          <img
            className={`max-w-sm rounded mx-auto transition-all mb-5 duration-500 ${selectedFilter}`}
            src={image}
            alt=""
          />
          {/* === Image Filter Buttons === */}
          {isImageLoaded && (
            <div className="flex flex-wrap justify-center gap-2 mt-4">
              {[
                { name: "None", class: "filter-none" },
                { name: "Grayscale", class: "filter-grayscale" },
                { name: "Sepia", class: "filter-sepia" },
                { name: "Contrast", class: "filter-contrast" },
                { name: "Warm", class: "filter-warm" },
                { name: "Cool", class: "filter-cool" },
                { name: "Vintage", class: "filter-vintage" },
              ].map((filter) => (
                <button
                  key={filter.class}
                  type="button" // ✅ important: prevents form submission
                  onClick={() => setSelectedFilter(filter.class)}
                  className={`px-4 py-2 rounded-full text-sm transition-all duration-200 ${
                    selectedFilter === filter.class
                      ? "bg-violet-500 text-white"
                      : "bg-zinc-200 text-black hover:bg-zinc-300"
                  }`}
                >
                  {filter.name}
                </button>
              ))}
            </div>
          )}

          <span
            className={`absolute bottom-0 left-0 h-1 bg-violet-400 ${
              loading ? "w-full transition-all duration-[10s]" : "w-0"
            }`}
          ></span>
        </div>
        <p className={!loading ? "hidden" : ""}>Loading...</p>
      </div>

      {/* Input & Buttons */}
      {!isImageLoaded && (
        <div className="w-full max-w-3xl space-y-4">
          <div className="relative bg-neutral-500 text-white rounded-3xl p-1 shadow-lg">
            <div className="flex items-start gap-2">
              <textarea
                onChange={(e) => setInput(e.target.value)}
                value={input}
                placeholder="Describe what you want to generate"
                rows={1}
                className="flex-1 bg-transparent outline-none px-6 py-3 resize-none overflow-hidden ph-color"
                style={{
                  minHeight: "48px",
                  maxHeight: "200px",
                  height: "auto",
                }}
                onInput={(e) => {
                  const target = e.target;
                  target.style.height = "auto";
                  target.style.height =
                    Math.min(target.scrollHeight, 200) + "px";
                }}
              />
              <button
                type="submit"
                disabled={loading || enhancing || !input.trim()}
                className={`${
                  loading || !input.trim()
                    ? "bg-gray-600"
                    : "bg-zinc-900 hover:bg-zinc-800"
                } px-8 py-3 rounded-full whitespace-nowrap transition-colors disabled:cursor-not-allowed flex-shrink-0`}
              >
                {loading ? "Generating..." : "Generate"}
              </button>
            </div>
          </div>

          {input && (
            <div className="flex justify-center">
              <button
                type="button"
                onClick={() => handleEnhancePrompt(input)}
                disabled={enhancing}
                className="p-3 px-5 rounded-xl bg-white border border-purple-200 hover:border-purple-300 hover:bg-gray-50 hover:shadow-lg transition-all duration-300 transform hover:scale-105 active:scale-95 flex items-center gap-3 disabled:opacity-50 disabled:cursor-not-allowed disabled:transform-none"
              >
                <Sparkles className="w-5 h-5 text-purple-500" />
                <span className="bg-gradient-to-br from-violet-500 via-purple-500 to-fuchsia-500 bg-clip-text text-transparent font-medium">
                  {enhancing ? "Enhancing..." : "Enhance prompt with AI"}
                </span>
              </button>
            </div>
          )}
        </div>
      )}

      {isImageLoaded && (
        <div className="flex flex-wrap gap-2 justify-center items-center text-white text-sm p-0.5 mt-10 rounded-full">
          <p
            onClick={() => setIsImageLoaded(false)}
            className="bg-transparent border border-zinc-900 text-black px-8 py-3 rounded-full cursor-pointer"
          >
            Generate Another
          </p>
          <a
            onClick={downloadFilteredImage}
            className="bg-zinc-900 px-10 py-3 rounded-full cursor-pointer text-white"
          >
            Download
          </a>
          <button
            type="button"
            onClick={handleShare}
            className="bg-violet-500 hover:bg-violet-600 text-white px-10 py-3 rounded-full cursor-pointer"
          >
            Share
          </button>
        </div>
      )}
    </motion.form>
  );
};

export default Result;
